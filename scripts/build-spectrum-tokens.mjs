#!/usr/bin/env node
// Generates apps/web/app/spectrum-tokens.css from the @adobe/spectrum-tokens
// package — a curated subset of Spectrum 2 primitives exposed as namespaced
// `--s2-*` CSS custom properties.
//
// Phase 0 of the Spectrum migration: these tokens are ADDITIVE and namespaced;
// nothing consumes them yet, so regenerating/importing them produces no visual
// change. Phase 2 aliases the app's semantic tokens (--ops-*, --color-*, radii,
// spacing, type scale) onto these values to flip the look in one controlled place.
//
// Re-run with: npm run build:tokens
import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
// The package's exports map blocks require.resolve on its files, so resolve the
// hoisted node_modules path directly (root first, then the web workspace).
const candidates = [
  resolve(here, '../node_modules/@adobe/spectrum-tokens/src'),
  resolve(here, '../apps/web/node_modules/@adobe/spectrum-tokens/src'),
]
const tokenDir = candidates.find(existsSync)
if (!tokenDir) {
  console.error('[spectrum-tokens] @adobe/spectrum-tokens not found; run npm install')
  process.exit(1)
}
const outFile = resolve(here, '../apps/web/app/spectrum-tokens.css')

const load = (name) => JSON.parse(readFileSync(`${tokenDir}/${name}`, 'utf8'))
const layout = load('layout.json')
const typography = load('typography.json')
const palette = load('color-palette.json')

const isDim = (k) => /^spacing-\d+$/.test(k) || /^corner-radius-(0|\d+|full)$/.test(k)
const isFontSize = (k) => /^font-size-\d+$/.test(k)
// Gray ramp + the hue ramps we map to OSHA-coded semantics later.
const isColor = (k) => /^(gray|blue|red|green|orange|yellow)-\d+$/.test(k)

const light = []
const dark = []

function pushDimension(obj) {
  for (const [k, v] of Object.entries(obj)) {
    if (k.startsWith('$') || typeof v !== 'object' || v === null) continue
    if ((isDim(k) || isFontSize(k)) && typeof v.value === 'string') {
      light.push(`  --s2-${k}: ${v.value};`)
    }
  }
}

pushDimension(layout)
pushDimension(typography)

for (const [k, v] of Object.entries(palette)) {
  if (k.startsWith('$') || !isColor(k) || typeof v !== 'object' || v === null) continue
  const l = v.sets?.light?.value
  const d = v.sets?.dark?.value
  if (typeof l === 'string') light.push(`  --s2-${k}: ${l};`)
  if (typeof d === 'string') dark.push(`  --s2-${k}: ${d};`)
}

light.sort()
dark.sort()

const out = `/* GENERATED by scripts/build-spectrum-tokens.mjs — do not edit by hand.
   Curated Spectrum 2 primitives (@adobe/spectrum-tokens) as namespaced --s2-*
   custom properties. Additive + namespaced: nothing consumes these yet, so this
   file is visually inert until Phase 2 of the Spectrum migration aliases the
   app's semantic tokens onto them. Regenerate with: npm run build:tokens */

:root {
${light.join('\n')}
}

.dark {
${dark.join('\n')}
}
`

writeFileSync(outFile, out)
console.log(`[spectrum-tokens] wrote ${outFile} (${light.length} light, ${dark.length} dark decls)`)
